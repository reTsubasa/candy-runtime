#!/usr/bin/env python3
"""Materialize/check the public PacketPort package without private Core code.

Core owns the development source; Runtime consumes a fixed public source
package. Normal verification needs only this checkout. Refresh is explicit.
"""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "shared/vendor/candy-packet-port"
PUBLIC_DEPENDENCIES = {"libc", "nix", "serde", "serde_json", "tokio", "tracing", "tempfile"}


def digest(data):
    return hashlib.sha256(data).hexdigest()


def tree_digest(files):
    h = hashlib.sha256()
    for name, data in sorted(files.items()):
        encoded = name.encode()
        h.update(len(encoded).to_bytes(8, "little"))
        h.update(encoded)
        h.update(len(data).to_bytes(8, "little"))
        h.update(data)
    return h.hexdigest()


def literal(value):
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, list):
        return "[" + ", ".join(literal(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{key} = {literal(item)}" for key, item in sorted(value.items())) + " }"
    raise ValueError(f"unsupported public package metadata: {type(value)}")


def refresh(core):
    core = core.resolve()
    origin = core / "crates/candy-packet-port"
    manifest_bytes = (origin / "Cargo.toml").read_bytes()
    manifest = tomllib.loads(manifest_bytes.decode())
    workspace = tomllib.loads((core / "Cargo.toml").read_text())["workspace"]
    lines = ["# Generated by scripts/packet_port_package.py; do not edit the vendored source.", "[package]"]
    for key, value in manifest["package"].items():
        if isinstance(value, dict) and value.get("workspace"):
            value = workspace["package"][key]
        lines.append(f"{key} = {literal(value)}")
    lines.extend(["", "[workspace]", ""])
    for section in ("dependencies", "dev-dependencies"):
        lines.append(f"[{section}]")
        for key, value in manifest.get(section, {}).items():
            if key not in PUBLIC_DEPENDENCIES:
                raise ValueError(f"private or unknown dependency {key}")
            if isinstance(value, dict) and value.get("workspace"):
                base = workspace["dependencies"][key]
                overrides = {name: item for name, item in value.items() if name != "workspace"}
                if overrides:
                    base = {"version": base} if isinstance(base, str) else dict(base)
                    for name, item in overrides.items():
                        base[name] = sorted(set(base.get(name, []) + item)) if name == "features" else item
                value = base
            if isinstance(value, dict) and ("path" in value or "git" in value):
                raise ValueError(f"public dependency {key} is not independently resolvable")
            lines.append(f"{key} = {literal(value)}")
        lines.append("")
    source = {"Cargo.toml": manifest_bytes}
    source.update({path.relative_to(origin).as_posix(): path.read_bytes() for path in sorted((origin / "src").rglob("*.rs"))})
    files = dict(source)
    files["Cargo.toml"] = "\n".join(lines).encode()
    PACKAGE.mkdir(parents=True, exist_ok=True)
    existing = {p.relative_to(PACKAGE).as_posix() for p in PACKAGE.rglob("*") if p.is_file()}
    for old in existing - set(files) - {"provenance.json"}:
        (PACKAGE / old).unlink()
    for name, data in files.items():
        path = PACKAGE / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    head = subprocess.check_output(["git", "-C", str(core), "rev-parse", "HEAD"], text=True).strip()
    provenance = {
        "schema_version": 1,
        "package": "candy-packet-port",
        "origin": "https://github.com/reTsubasa/candy-core",
        "origin_path": "crates/candy-packet-port",
        "origin_base_commit": head,
        "origin_worktree_content_sha256": tree_digest(source),
        "package_content_sha256": tree_digest(files),
        "files": {name: digest(data) for name, data in sorted(files.items())},
        "source_files": {name: digest(data) for name, data in sorted(source.items())},
        "note": "Fixed public source package from a development worktree; base commit alone is not its content identity.",
    }
    (PACKAGE / "provenance.json").write_text(json.dumps(provenance, indent=2, sort_keys=True) + "\n")


def verify():
    record = json.loads((PACKAGE / "provenance.json").read_text())
    if record["schema_version"] != 1 or record["package"] != "candy-packet-port":
        raise ValueError("invalid public package provenance")
    paths = [path for path in PACKAGE.rglob("*") if path.is_file() or path.is_symlink()]
    if any(path.is_symlink() for path in paths):
        raise ValueError("public package may not contain symlinks")
    files = {path.relative_to(PACKAGE).as_posix(): path.read_bytes() for path in paths if path.name != "provenance.json"}
    if {name: digest(data) for name, data in sorted(files.items())} != record["files"]:
        raise ValueError("public PacketPort content differs from fixed provenance")
    if tree_digest(files) != record["package_content_sha256"]:
        raise ValueError("public PacketPort package digest differs")
    for name, expected in record["source_files"].items():
        if name != "Cargo.toml" and digest(files[name]) != expected:
            raise ValueError("vendored implementation differs from authoritative public source")
    manifest = tomllib.loads(files["Cargo.toml"].decode())
    for section in ("dependencies", "dev-dependencies"):
        for name, dependency in manifest.get(section, {}).items():
            if name not in PUBLIC_DEPENDENCIES:
                raise ValueError(f"private dependency {name}")
            if isinstance(dependency, dict) and any(key in dependency for key in ("path", "git", "workspace")):
                raise ValueError("vendored public package still depends on another checkout")
    print(f"Public PacketPort package passed: {record['package_content_sha256']}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--core-dir", type=Path, help="explicitly refresh from the authoritative public crate")
    args = parser.parse_args()
    if args.core_dir:
        refresh(args.core_dir)
    verify()
